import 'dotenv/config';
import pg from 'pg';

const { Pool } = pg;

const connectionString = process.env.DATABASE_URL;

if (!connectionString) {
  throw new Error('DATABASE_URL is missing.');
}

const databaseUrl = new URL(connectionString);
const hostname = databaseUrl.hostname;
const hostOverride = process.env.DATABASE_HOST_OVERRIDE;

const pool = new Pool({
  host: hostOverride || hostname,
  port: Number(databaseUrl.port || 5432),
  database: decodeURIComponent(databaseUrl.pathname.slice(1)),
  user: decodeURIComponent(databaseUrl.username),
  password: decodeURIComponent(databaseUrl.password),

  ssl: {
    rejectUnauthorized: false,
    servername: hostname,
  },

  max: 5,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 15000,
});

pool.on('error', (error) => {
  console.error('Unexpected PostgreSQL pool error:', error.message);
});

const db = {
  query(text, values = []) {
    return pool.query(text, values);
  },

  async transaction(callback) {
    const client = await pool.connect();

    try {
      await client.query('BEGIN');
      const result = await callback(client);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  },

  async initialize() {
    if (!process.env.DATABASE_URL) {
      throw new Error(
        'DATABASE_URL is missing. Configure your Neon PostgreSQL connection first.',
      );
    }

    await pool.query(`
      CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        google_sub TEXT UNIQUE
      );

      CREATE TABLE IF NOT EXISTS subscriptions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        plan TEXT NOT NULL DEFAULT 'free'
          CHECK (plan IN ('free', 'pro')),
        status TEXT NOT NULL DEFAULT 'active'
          CHECK (status IN ('active', 'expired', 'cancelled', 'pending')),
        starts_at TIMESTAMPTZ,
        expires_at TIMESTAMPTZ,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE IF NOT EXISTS payments (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        subscription_id BIGINT REFERENCES subscriptions(id),
        amount_tzs BIGINT NOT NULL CHECK (amount_tzs > 0),
        currency TEXT NOT NULL DEFAULT 'TZS',
        provider TEXT,
        provider_reference TEXT UNIQUE,
        status TEXT NOT NULL DEFAULT 'pending'
          CHECK (status IN ('pending', 'verified', 'failed', 'refunded')),
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        verified_at TIMESTAMPTZ
      );

      CREATE TABLE IF NOT EXISTS unique_visitors (
        visitor_id TEXT PRIMARY KEY,
        first_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );

      CREATE INDEX IF NOT EXISTS idx_subscriptions_user
        ON subscriptions(user_id);

      CREATE INDEX IF NOT EXISTS idx_payments_user
        ON payments(user_id);

      CREATE UNIQUE INDEX IF NOT EXISTS idx_users_google_sub
        ON users(google_sub);
    `);

    console.log('Neon PostgreSQL schema initialized successfully.');
  },

  async close() {
    await pool.end();
  },
};

export default db;
